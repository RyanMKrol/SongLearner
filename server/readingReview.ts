// Dev-server endpoint that asks Claude to check how the kanji in a Japanese song are sung.
//
// The dictionary gives the standard reading of each word, but lyricists often give words a
// special reading (瞬間 sung as "toki") that only appears as small kana in the official lyrics.
// Claude reviews the song, can look up lyric sites that show those readings, and reports which
// words are sung differently. It runs server-side so the API key never reaches the browser.
import Anthropic from '@anthropic-ai/sdk'
import type { IncomingMessage, ServerResponse } from 'node:http'
import type { Plugin } from 'vite'

const MODEL = 'claude-opus-5-5'
const MAX_REQUESTS = 6

export interface ReviewWord {
  source: string
  standard: string
}

export interface ReviewRequest {
  title: string
  artist: string
  album: string
  /** The Japanese lyric lines, for context. */
  lines: string[]
  /** Every distinct Japanese word in the song with its dictionary romaji. */
  words: ReviewWord[]
}

export interface ReviewSuggestion {
  source: string
  reading: string
  confidence: 'high' | 'medium' | 'low'
  reason: string
}

export interface ReviewResponse {
  suggestions: ReviewSuggestion[]
  notes: string
  model: string
}

const SYSTEM = `You help a karaoke learner who can't read kanji. They sing Japanese songs from romaji generated by a dictionary, which gives the standard reading of each word. Your job is to find the words in this song that are sung differently from that standard reading.

Common reasons a sung reading differs:
- The lyricist gave the word a special reading, shown as furigana in the official lyrics (for example 瞬間 sung as "toki", 永遠 as "towa", 運命 as "sadame", 地球 as "hoshi", 本気 as "maji").
- The dictionary picked the wrong one of several valid readings for this context (for example 何 as "nan" vs "nani", 行く as "iku" vs "yuku", 明日 as "ashita" vs "asu", 私 as "watashi" vs "atashi").
- A name or unusual word the dictionary doesn't know.

How to work:
- If you can, use web search to find this song's lyrics on a site that shows furigana (for example utaten.com, uta-net.com or j-lyric.net) and check the readings there. Official furigana beats your own judgment.
- Only report words whose sung reading differs from the dictionary romaji given. Don't report words that are already right.
- The "source" of each suggestion must be copied exactly from the word list provided, character for character.
- Give the reading in lowercase Hepburn romaji the way it's sung (long vowels written out, e.g. "toukyou", particles as pronounced).
- Confidence: "high" when official furigana or an unambiguous convention confirms it, "medium" when it's very likely from context and convention, "low" when it's a plausible guess.
- Keep each reason to one short sentence. Never quote or reproduce the song's lyrics in your answer; refer to words only.

When you're done, call submit_readings exactly once with your findings. If everything already looks right, call it with an empty list.`

const SUBMIT_TOOL: Anthropic.Beta.BetaTool = {
  name: 'submit_readings',
  description: 'Submit the words in this song whose sung reading differs from the dictionary romaji.',
  strict: true,
  input_schema: {
    type: 'object',
    properties: {
      suggestions: {
        type: 'array',
        items: {
          type: 'object',
          properties: {
            source: { type: 'string', description: 'The word exactly as it appears in the provided word list.' },
            reading: { type: 'string', description: 'How it is sung, in lowercase Hepburn romaji.' },
            confidence: { type: 'string', enum: ['high', 'medium', 'low'] },
            reason: { type: 'string', description: 'One short sentence. Do not quote lyrics.' },
          },
          required: ['source', 'reading', 'confidence', 'reason'],
          additionalProperties: false,
        },
      },
      notes: {
        type: 'string',
        description: 'One or two sentences on how you checked (for example which source had furigana).',
      },
    },
    required: ['suggestions', 'notes'],
    additionalProperties: false,
  },
}

function userPrompt(req: ReviewRequest): string {
  const words = req.words.map((w) => `${w.source} → ${w.standard}`).join('\n')
  return `Song: "${req.title}" by ${req.artist} (album: ${req.album})

The lyrics, line by line:
${req.lines.join('\n')}

Every distinct Japanese word in the song, with the dictionary romaji currently shown:
${words}

Which of these words are sung differently? Check, then call submit_readings.`
}

interface SubmitInput {
  suggestions: ReviewSuggestion[]
  notes: string
}

/** Runs the review, resuming web-search turns that pause, until Claude submits its findings. */
export async function reviewReadings(client: Anthropic, req: ReviewRequest): Promise<ReviewResponse> {
  const messages: Anthropic.Beta.BetaMessageParam[] = [{ role: 'user', content: userPrompt(req) }]

  for (let i = 0; i < MAX_REQUESTS; i++) {
    const response = await client.beta.messages.create({
      model: MODEL,
      max_tokens: 16000,
      // If the model declines, the API retries on a fallback model within the same call.
      betas: ['server-side-fallback-2026-07-01'],
      fallbacks: 'default',
      output_config: { effort: 'high' },
      system: SYSTEM,
      tools: [{ type: 'web_search_20260209', name: 'web_search', max_uses: 5 }, SUBMIT_TOOL],
      tool_choice: { type: 'auto' },
      messages,
    })

    if (response.stop_reason === 'refusal') {
      throw new Error('Claude declined to review this song.')
    }

    const submit = response.content.find(
      (block): block is Anthropic.Beta.BetaToolUseBlock => block.type === 'tool_use' && block.name === 'submit_readings',
    )
    if (submit) {
      const input = submit.input as SubmitInput
      return { ...sanitise(input, req), model: response.model }
    }

    messages.push({ role: 'assistant', content: response.content })
    if (response.stop_reason !== 'pause_turn') {
      // It finished without submitting; ask once more. (A paused web-search turn resumes by itself.)
      messages.push({ role: 'user', content: 'Please call submit_readings with your findings now.' })
    }
  }
  throw new Error('Claude did not finish the review.')
}

/** Keeps only suggestions for words that exist in the song and actually change the reading. */
function sanitise(input: SubmitInput, req: ReviewRequest): Omit<ReviewResponse, 'model'> {
  const standards = new Map(req.words.map((w) => [w.source, w.standard]))
  const seen = new Set<string>()
  const suggestions = (input.suggestions ?? [])
    .map((s) => ({ ...s, reading: s.reading.trim().toLowerCase() }))
    .filter((s) => {
      const standard = standards.get(s.source)
      if (standard === undefined || !s.reading || s.reading === standard || seen.has(s.source)) return false
      seen.add(s.source)
      return true
    })
  return { suggestions, notes: input.notes ?? '' }
}

async function readJson(req: IncomingMessage): Promise<unknown> {
  const chunks: Buffer[] = []
  for await (const chunk of req) chunks.push(chunk as Buffer)
  return JSON.parse(Buffer.concat(chunks).toString('utf8'))
}

function send(res: ServerResponse, status: number, body: unknown): void {
  res.statusCode = status
  res.setHeader('Content-Type', 'application/json')
  res.end(JSON.stringify(body))
}

function isReviewRequest(value: unknown): value is ReviewRequest {
  const v = value as ReviewRequest
  return (
    typeof v === 'object' &&
    v !== null &&
    typeof v.title === 'string' &&
    Array.isArray(v.lines) &&
    Array.isArray(v.words) &&
    v.words.every((w) => typeof w?.source === 'string' && typeof w?.standard === 'string')
  )
}

/** Adds POST /api/review-readings to the Vite dev and preview servers. */
export function readingReviewPlugin(apiKey: string | undefined): Plugin {
  const client = apiKey ? new Anthropic({ apiKey }) : null

  const handler = async (req: IncomingMessage, res: ServerResponse, next: () => void) => {
    if (req.url !== '/api/review-readings') return next()
    if (req.method !== 'POST') return send(res, 405, { error: 'method_not_allowed' })
    if (!client) {
      return send(res, 501, {
        error: 'no_api_key',
        message: 'Add ANTHROPIC_API_KEY to .env.local and restart the dev server to turn on reading checks.',
      })
    }
    try {
      const body = await readJson(req)
      if (!isReviewRequest(body)) return send(res, 400, { error: 'bad_request', message: 'Malformed review request.' })
      send(res, 200, await reviewReadings(client, body))
    } catch (e) {
      if (e instanceof Anthropic.AuthenticationError) {
        send(res, 401, { error: 'auth', message: 'Anthropic rejected the API key in .env.local.' })
      } else if (e instanceof Anthropic.RateLimitError) {
        send(res, 429, { error: 'rate_limited', message: 'Rate limited by the Anthropic API. Try again shortly.' })
      } else if (e instanceof Anthropic.APIError) {
        send(res, 502, { error: 'api', message: `Anthropic API error ${e.status ?? ''}: ${e.message}` })
      } else {
        send(res, 500, { error: 'failed', message: e instanceof Error ? e.message : String(e) })
      }
    }
  }

  return {
    name: 'songlearner-reading-review',
    configureServer(server) {
      server.middlewares.use((req, res, next) => void handler(req, res, next))
    },
    configurePreviewServer(server) {
      server.middlewares.use((req, res, next) => void handler(req, res, next))
    },
  }
}
